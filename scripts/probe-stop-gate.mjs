#!/usr/bin/env node
// scripts/probe-stop-gate.mjs
// ----------------------------------------------------------------------------
// Two jobs, because the probe needs somewhere to be mounted and something to read it:
//
//   node scripts/probe-stop-gate.mjs            generate the mount patch + print the command
//   node scripts/probe-stop-gate.mjs --report   read the evidence and return a verdict
//
// WHY A GENERATED PATCH: a patch entry names a module, and the probe is a file in this
// checkout, so the specifier is machine-specific. `!!js` expressions are NOT evaluated in
// this position (verified: the loader prints them verbatim), and a relative specifier
// resolves against the PROFILE directory, not the cwd. So the path is written at run time
// rather than committed — the repo stays portable and the patch is always correct.
//
// The probe itself is dsh-plugin/probes/stop-gate.mjs; see its header for what it records
// and why it is safe to run.
// ----------------------------------------------------------------------------

import { appendFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = resolve('.');
const PROBE = join(ROOT, 'dsh-plugin', 'probes', 'stop-gate.mjs');
const OUT_DIR = join(ROOT, 'artifacts', 'probe');
const PATCH = join(OUT_DIR, 'stop-gate.patch.yml');
const EVIDENCE = process.env.PB_STOP_GATE_PROBE_FILE
  || join(process.env.TEMP || process.env.TMPDIR || '/tmp', 'pb-stop-gate-probe.ndjson');

// --- report mode -------------------------------------------------------------
if (process.argv.includes('--report')) {
  if (!existsSync(EVIDENCE)) {
    console.log(`No evidence at ${EVIDENCE}\nRun the probe first:\n  node scripts/probe-stop-gate.mjs`);
    process.exit(1);
  }
  const rows = readFileSync(EVIDENCE, 'utf8').split(/\r?\n/).filter(Boolean).flatMap((l) => {
    try { return [JSON.parse(l)]; } catch { return []; }
  });
  const fires = rows.filter((r) => r.kind === 'turn-stopping');
  const errors = rows.filter((r) => r.kind === 'probe-error');
  const started = rows.find((r) => r.kind === 'probe-start');

  console.log(`evidence: ${EVIDENCE}`);
  console.log(`probe started: ${started ? started.at : 'NO — the plugin never loaded'}`);
  if (started) console.log(`enabled: ${started.enabled} · max steers: ${started.maxSteers}`);
  console.log(`turn-stopping fires: ${fires.length}`);
  for (const r of fires) {
    console.log(`  turn ${r.turn} · fire ${r.fire} · ${r.action} · agent arrived: ${r.agentArrived} · canSteer: ${r.canSteer} · inboxBefore: ${r.inboxBefore}`);
  }
  if (errors.length) for (const e of errors) console.log(`  PROBE ERROR: ${e.message}`);

  // The verdict. A second fire for the SAME turn is only reachable if the first steer kept
  // the turn open — that is the whole experiment.
  const byTurn = new Map();
  for (const r of fires) byTurn.set(`${r.agent}\u0000${r.turn}`, (byTurn.get(`${r.agent}\u0000${r.turn}`) ?? 0) + 1);
  const continued = [...byTurn.values()].some((n) => n >= 2);

  console.log('');
  if (!started) {
    console.log('VERDICT: INCONCLUSIVE — the probe plugin never loaded (check the --patch mount).');
    process.exit(1);
  }
  if (continued) {
    console.log('VERDICT: VERIFIED — a turn-stopping handler steered and the turn ran another step.');
    console.log('The Stop gate is real: the runtime can refuse to let a turn end unverified.');
  } else if (fires.length === 0) {
    console.log('VERDICT: INCONCLUSIVE — the event never fired. No turn reached its stopping point');
    console.log('with an empty inbox, or the session ended first. Run one more full turn.');
    process.exit(1);
  } else {
    console.log('VERDICT: NOT VERIFIED — the handler ran, but no second fire for the same turn');
    console.log('appeared, so steering did not continue the turn. Do not build the gate on it.');
    process.exit(1);
  }
  process.exit(0);
}

// --- generate mode -----------------------------------------------------------
if (!existsSync(PROBE)) {
  console.error(`Probe not found: ${PROBE}`);
  process.exit(1);
}
mkdirSync(OUT_DIR, { recursive: true });

const specifier = pathToFileURL(PROBE).href;
writeFileSync(PATCH, [
  '# GENERATED by scripts/probe-stop-gate.mjs — do not commit; regenerated on demand.',
  '# Mounts the turn-stopping probe on top of a profile without modifying it on disk.',
  '- insert:',
  '    - id: stop-gate-probe',
  `      name: '${specifier}'`,
  '',
].join('\n'), 'utf8');

// A header row makes the evidence self-describing: a reader can tell which probe build and
// which module actually produced it, not just when.
try {
  mkdirSync(dirname(EVIDENCE), { recursive: true });
  appendFileSync(EVIDENCE, `${JSON.stringify({
    kind: 'probe-mounted', at: new Date().toISOString(), probe: specifier, patch: PATCH, node: process.version,
  })}\n`, 'utf8');
} catch { /* evidence is best-effort */ }

console.log(`probe:   ${specifier}`);
console.log(`patch:   ${PATCH}`);
console.log(`evidence: ${EVIDENCE}`);
console.log('');
console.log('Run a session with the probe mounted (this is the step that costs a model call):');
console.log('');
console.log(`  dsh --profile web --patch "${PATCH}"`);
console.log('');
console.log('Then ask it to do one small thing that finishes, so the turn reaches its stopping');
console.log('point. Afterwards read the verdict:');
console.log('');
console.log('  node scripts/probe-stop-gate.mjs --report');
console.log('');
console.log('The probe steers at most once per turn and twice per process, never throws, and is');
console.log('disabled entirely with PB_STOP_GATE_PROBE=off.');
